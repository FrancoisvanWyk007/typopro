import { HANDS, judgmentHand, judgmentKind, type Hand, type Judgment, type JudgmentKind } from './types';

/** Contribution of each judgment to accuracy and to the rolling instrument score. */
export const JUDGMENT_VALUE: Record<Exclude<JudgmentKind, 'stray'>, number> = {
  perfect: 1,
  great: 0.85,
  good: 0.6,
  wrong: 0,
  miss: 0,
};

export interface ScoreConfig {
  /** EMA weight of each judged event in the rolling score (0..1). */
  alpha: number;
  /** EMA weight of a stray keystroke pulling the hand's instrument toward 0. */
  strayAlpha: number;
  /** Rolling score every instrument starts with. */
  initialScore: number;
}

export const DEFAULT_SCORE_CONFIG: ScoreConfig = { alpha: 0.25, strayAlpha: 0.06, initialScore: 0.3 };

export type JudgmentCounts = Record<JudgmentKind, number>;

interface HandStats {
  judged: number;
  valueSum: number;
  offsetSum: number;
  hits: number;
}

export interface ScoreSummary {
  judged: number;
  accuracy: number | null;
  combo: number;
  maxCombo: number;
  counts: JudgmentCounts;
  hands: Record<Hand, { judged: number; accuracy: number | null; meanOffsetMs: number | null }>;
}

const emptyCounts = (): JudgmentCounts => ({ perfect: 0, great: 0, good: 0, wrong: 0, miss: 0, stray: 0 });
const emptyHand = (): HandStats => ({ judged: 0, valueSum: 0, offsetSum: 0, hits: 0 });

/**
 * Accumulates judgments into combo/accuracy totals and per-instrument rolling
 * scores. Rolling scores are an exponential moving average over judged events,
 * so a miss (generated by the clock, not by input) lowers the score just like
 * a bad keystroke does.
 */
export class ScoreTracker {
  readonly config: ScoreConfig;
  private readonly handInstrument: Record<Hand, string>;
  private readonly instruments: readonly string[];
  private scores = new Map<string, number>();
  private counts = emptyCounts();
  private hands: Record<Hand, HandStats> = { left: emptyHand(), right: emptyHand() };
  private combo = 0;
  private maxCombo = 0;

  constructor(instruments: readonly string[], handInstrument: Record<Hand, string>, config = DEFAULT_SCORE_CONFIG) {
    this.instruments = instruments;
    this.handInstrument = handInstrument;
    this.config = config;
    this.reset();
  }

  reset(): void {
    this.scores = new Map(this.instruments.map((id) => [id, this.config.initialScore]));
    this.counts = emptyCounts();
    this.hands = { left: emptyHand(), right: emptyHand() };
    this.combo = 0;
    this.maxCombo = 0;
  }

  /** Apply one judgment. Returns the instrument whose rolling score changed. */
  apply(j: Judgment): string {
    const kind = judgmentKind(j);
    this.counts[kind]++;

    if (j.kind === 'stray') {
      const id = this.handInstrument[j.hand];
      this.nudge(id, 0, this.config.strayAlpha);
      return id;
    }

    const value = JUDGMENT_VALUE[kind as Exclude<JudgmentKind, 'stray'>];
    const hand = this.hands[judgmentHand(j)];
    hand.judged++;
    hand.valueSum += value;
    if (j.kind === 'hit') {
      hand.hits++;
      hand.offsetSum += j.offsetMs;
      this.combo++;
      this.maxCombo = Math.max(this.maxCombo, this.combo);
    } else {
      this.combo = 0;
    }
    this.nudge(j.event.instrument, value, this.config.alpha);
    return j.event.instrument;
  }

  instrumentScore(id: string): number {
    return this.scores.get(id) ?? this.config.initialScore;
  }

  summary(): ScoreSummary {
    const judged = HANDS.reduce((n, h) => n + this.hands[h].judged, 0);
    const valueSum = HANDS.reduce((n, h) => n + this.hands[h].valueSum, 0);
    const hand = (h: Hand) => {
      const s = this.hands[h];
      return {
        judged: s.judged,
        accuracy: s.judged ? s.valueSum / s.judged : null,
        meanOffsetMs: s.hits ? s.offsetSum / s.hits : null,
      };
    };
    return {
      judged,
      accuracy: judged ? valueSum / judged : null,
      combo: this.combo,
      maxCombo: this.maxCombo,
      counts: { ...this.counts },
      hands: { left: hand('left'), right: hand('right') },
    };
  }

  private nudge(id: string, value: number, alpha: number): void {
    const prev = this.instrumentScore(id);
    this.scores.set(id, prev + alpha * (value - prev));
  }
}

/**
 * Map a rolling score (0..1) to a linear gain multiplier. A floor keeps a
 * faint ghost of the instrument audible so the player hears what they are
 * missing; the curve makes good play clearly louder than mediocre play.
 */
export function gainForScore(score: number, floor = 0.05): number {
  const s = Math.min(1, Math.max(0, score));
  return floor + (1 - floor) * Math.pow(s, 1.6);
}

export function gradeFor(accuracy: number | null): string {
  if (accuracy === null) return '–';
  if (accuracy >= 0.95) return 'S';
  if (accuracy >= 0.88) return 'A';
  if (accuracy >= 0.78) return 'B';
  if (accuracy >= 0.65) return 'C';
  return 'D';
}
